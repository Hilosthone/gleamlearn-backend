const CUE_TIME = /^\s*(?:(\d{1,2}):)?(\d{1,2}):(\d{2})[.,](\d{1,3})\s*-->\s*(?:(\d{1,2}):)?(\d{1,2}):(\d{2})[.,](\d{1,3})/;

/**
 * A VTT or SRT caption file → `[mm:ss] text` lines (the same form as fetched transcripts, so timestamp links work).
 * Markup (<c>, <i>, <00:00:01.000>), cue settings, NOTE/STYLE blocks and consecutive duplicate lines (rolling
 * automatic captions) are removed. Returns '' when the file has no cues.
 */
export function parseCaptionFile(content: string): string {
  const text = content.replace(/^﻿/, '').replace(/\r\n?/g, '\n').replaceAll('\u0000', '');
  const blocks = text.split(/\n{2,}/);
  const out: string[] = [];
  let last = '';
  for (const block of blocks) {
    const lines = block.split('\n');
    const at = lines.findIndex((l) => CUE_TIME.test(l));
    if (at < 0) continue; // header, NOTE, STYLE, REGION or a stray index
    const m = lines[at].match(CUE_TIME)!;
    const seconds = Number(m[1] ?? 0) * 3600 + Number(m[2]) * 60 + Number(m[3]);
    const words = lines
      .slice(at + 1)
      .join(' ')
      .replace(/<[^>]*>/g, '')
      .replace(/&amp;/g, '&')
      .replace(/&lt;/g, '<')
      .replace(/&gt;/g, '>')
      .replace(/&quot;/g, '"')
      .replace(/&#39;|&apos;/g, "'")
      .replace(/&nbsp;/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
    if (!words || words === last) continue;
    last = words;
    out.push(`[${formatTimestamp(seconds)}] ${words}`);
  }
  return out.join('\n').slice(0, MAX_TRANSCRIPT_CHARS);
}

/** 'vtt', 'srt' or null, from the declared format or the content. */
export function captionFormat(content: string, declared?: string): 'vtt' | 'srt' | null {
  const d = declared?.toLowerCase().replace(/^\./, '');
  if (d === 'vtt' || d === 'srt') return d;
  const head = content.replace(/^﻿/, '').trimStart();
  if (head.startsWith('WEBVTT')) return 'vtt';
  if (/^\d+\s*\r?\n\s*\d{1,2}:\d{2}:\d{2},\d{3}\s*-->/.test(head)) return 'srt';
  return null;
}
