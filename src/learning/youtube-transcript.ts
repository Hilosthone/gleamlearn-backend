import {
  YoutubeTranscript,
  YoutubeTranscriptDisabledError,
  YoutubeTranscriptNotAvailableError,
  YoutubeTranscriptNotAvailableLanguageError,
  YoutubeTranscriptTooManyRequestError,
  YoutubeTranscriptVideoUnavailableError,
} from 'youtube-transcript';
import { formatTimestamp } from './grading.js';

/**
 * Fetching a video's captions from YouTube, with an honest reason when it fails.
 *
 * The youtube-transcript library swallows the real cause: when YouTube asks "confirm you're not a bot" its web
 * fallback reports that as "transcripts are disabled", and it always takes the first caption track. So we first ask
 * YouTube's player API (the same InnerTube call the library makes) for the video's playability and caption list,
 * classify the result, pick the best caption language, and only then let the library download and parse that track.
 * Everything shares one timeout. No paid service is involved.
 */

export const TRANSCRIPT_TIMEOUT_MS = 15_000;
export const MAX_TRANSCRIPT_CHARS = 200_000;

export type TranscriptFailureCode =
  | 'NO_CAPTIONS'
  | 'BLOCKED'
  | 'PRIVATE'
  | 'AGE_RESTRICTED'
  | 'UNAVAILABLE'
  | 'LANGUAGE_UNAVAILABLE'
  | 'TIMEOUT'
  | 'NETWORK'
  | 'DISABLED_ON_SERVER';

/** What the learner is told for each failure, and whether trying again later can help. */
export const TRANSCRIPT_FAILURES: Record<TranscriptFailureCode, { message: string; retryable: boolean }> = {
  NO_CAPTIONS: {
    message: 'This video has no captions on YouTube, so there is no transcript to fetch. Upload a caption file (VTT or SRT) or paste the transcript or your notes.',
    retryable: false,
  },
  BLOCKED: {
    message: 'YouTube refused to share the captions with our server right now (it sometimes blocks automated requests). Try again later, or upload a caption file or paste the transcript.',
    retryable: true,
  },
  PRIVATE: { message: 'This video is private, so its captions cannot be read. Paste the transcript or your notes instead.', retryable: false },
  AGE_RESTRICTED: {
    message: 'This video is age-restricted, so YouTube does not share its captions without signing in. Upload a caption file or paste the transcript instead.',
    retryable: false,
  },
  UNAVAILABLE: { message: 'This video is unavailable (it may have been removed or blocked in this region). Paste the transcript or your notes instead.', retryable: false },
  LANGUAGE_UNAVAILABLE: {
    message: 'The captions for this video could not be read in any supported language. Upload a caption file or paste the transcript instead.',
    retryable: false,
  },
  TIMEOUT: { message: 'YouTube took too long to respond. Try again in a moment, or upload a caption file or paste the transcript.', retryable: true },
  NETWORK: { message: 'We could not reach YouTube. Try again in a moment, or upload a caption file or paste the transcript.', retryable: true },
  DISABLED_ON_SERVER: { message: 'Transcripts cannot be fetched on this server. Upload a caption file or paste the transcript or your notes instead.', retryable: false },
};

export class TranscriptFetchError extends Error {
  constructor(
    readonly code: TranscriptFailureCode,
    readonly detail = '',
  ) {
    super(TRANSCRIPT_FAILURES[code].message);
  }
}

export interface CaptionTrack {
  languageCode: string;
  kind?: string; // 'asr' = generated automatically
  name?: string;
  baseUrl?: string;
}

export interface FetchedTranscript {
  lines: string;
  language: string;
  autoGenerated: boolean;
}

/** Manual captions beat automatic ones; English first, then the preferred languages, then whatever exists. */
export function pickTrack(tracks: CaptionTrack[], preferred: string[] = ['en']): CaptionTrack | null {
  const usable = tracks.filter((t) => t && typeof t.languageCode === 'string' && t.languageCode);
  if (!usable.length) return null;
  const rank = (t: CaptionTrack) => {
    const lang = t.languageCode.toLowerCase();
    const base = lang.split('-')[0];
    let i = preferred.findIndex((p) => p.toLowerCase() === lang);
    if (i < 0) i = preferred.findIndex((p) => p.toLowerCase().split('-')[0] === base);
    const langScore = i < 0 ? preferred.length : i;
    return langScore * 2 + (t.kind === 'asr' ? 1 : 0);
  };
  return [...usable].sort((a, b) => rank(a) - rank(b))[0];
}

/** InnerTube playability → failure (null when the video can be played). */
export function classifyPlayability(p: { status?: string; reason?: string; messages?: string[] } | undefined): TranscriptFailureCode | null {
  if (!p?.status || p.status === 'OK') return null;
  const why = `${p.reason ?? ''} ${(p.messages ?? []).join(' ')}`.toLowerCase();
  if (/not a bot|unusual traffic|captcha/.test(why)) return 'BLOCKED';
  if (/private/.test(why)) return 'PRIVATE';
  if (p.status === 'AGE_CHECK_REQUIRED' || p.status === 'AGE_VERIFICATION_REQUIRED' || /age|inappropriate/.test(why)) return 'AGE_RESTRICTED';
  if (p.status === 'LOGIN_REQUIRED') return 'BLOCKED'; // sign-in demanded for a public video: the server is being challenged
  return 'UNAVAILABLE';
}

/** A library or fetch error → failure. `probe` is what the player API said, when it answered. */
export function classifyError(err: unknown, probe: { playable: boolean; tracks: number } | null): TranscriptFailureCode {
  if (err instanceof TranscriptFetchError) return err.code;
  const name = (err as { name?: string })?.name;
  if (name === 'TimeoutError' || name === 'AbortError') return 'TIMEOUT';
  if (err instanceof YoutubeTranscriptTooManyRequestError) return 'BLOCKED';
  if (err instanceof YoutubeTranscriptVideoUnavailableError) return 'UNAVAILABLE';
  if (err instanceof YoutubeTranscriptNotAvailableLanguageError) return 'LANGUAGE_UNAVAILABLE';
  // "disabled": genuine only when the player API also reported a playable video with no captions;
  // otherwise it is the web page's bot check misreported by the library
  if (err instanceof YoutubeTranscriptDisabledError) return probe?.playable && probe.tracks === 0 ? 'NO_CAPTIONS' : 'BLOCKED';
  if (err instanceof YoutubeTranscriptNotAvailableError) return 'BLOCKED'; // the caption download was refused
  if (err instanceof TypeError) return 'NETWORK'; // fetch failed (DNS, connection reset, …)
  return 'BLOCKED';
}

/** youtube-transcript returns offsets in ms (srv3) or seconds (classic). Fractions mean seconds. */
export function toTranscriptLines(items: { text: string; offset: number }[]): string {
  const ms = items.length > 0 && items.every((i) => Number.isInteger(i.offset)) && items.some((i) => i.offset >= 1000);
  return items
    .map((i) => ({ s: ms ? i.offset / 1000 : i.offset, text: String(i.text ?? '').replace(/\s+/g, ' ').trim() }))
    .filter((i) => i.text)
    .map((i) => `[${formatTimestamp(i.s)}] ${i.text}`)
    .join('\n')
    .slice(0, MAX_TRANSCRIPT_CHARS);
}

const INNERTUBE_URL = 'https://www.youtube.com/youtubei/v1/player?prettyPrint=false';
const INNERTUBE_VERSION = '20.10.38';

/** One fetch with a shared deadline. */
const timed =
  (base: typeof fetch, signal: AbortSignal): typeof fetch =>
  (input, init) =>
    base(input, { ...init, signal: init?.signal ? AbortSignal.any([init.signal, signal]) : signal });

export async function fetchYoutubeTranscript(
  videoId: string,
  opts: { fetch?: typeof fetch; timeoutMs?: number; preferred?: string[]; fetchTrack?: typeof YoutubeTranscript.fetchTranscript } = {},
): Promise<FetchedTranscript> {
  const signal = AbortSignal.timeout(opts.timeoutMs ?? TRANSCRIPT_TIMEOUT_MS);
  const f = timed(opts.fetch ?? fetch, signal);
  const fetchTrack = opts.fetchTrack ?? YoutubeTranscript.fetchTranscript.bind(YoutubeTranscript);
  let probe: { playable: boolean; tracks: number } | null = null;
  let track: CaptionTrack | null = null;

  try {
    // 1. the player API: playability and caption list
    try {
      const r = await f(INNERTUBE_URL, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'User-Agent': `com.google.android.youtube/${INNERTUBE_VERSION} (Linux; U; Android 14)` },
        body: JSON.stringify({ context: { client: { clientName: 'ANDROID', clientVersion: INNERTUBE_VERSION } }, videoId }),
      });
      if (r.status === 429) throw new TranscriptFetchError('BLOCKED', 'player API 429');
      if (r.ok) {
        const data = (await r.json()) as {
          playabilityStatus?: { status?: string; reason?: string; messages?: string[] };
          captions?: { playerCaptionsTracklistRenderer?: { captionTracks?: CaptionTrack[] } };
        };
        const failure = classifyPlayability(data.playabilityStatus);
        if (failure) throw new TranscriptFetchError(failure, data.playabilityStatus?.status ?? '');
        const tracks = data.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
        probe = { playable: true, tracks: Array.isArray(tracks) ? tracks.length : 0 };
        if (!probe.tracks) throw new TranscriptFetchError('NO_CAPTIONS');
        track = pickTrack(tracks, opts.preferred);
        if (!track) throw new TranscriptFetchError('LANGUAGE_UNAVAILABLE');
      }
      // any other status: no verdict, the library's own attempts (player API then web page) decide
    } catch (err) {
      if (err instanceof TranscriptFetchError) throw err;
      const name = (err as { name?: string })?.name;
      if (name === 'TimeoutError' || name === 'AbortError') throw err;
      // a network/JSON error on the probe alone: let the library try its fallbacks
    }

    // 2. download and parse the chosen track (library), within the same deadline
    const items = await fetchTrack(videoId, { ...(track ? { lang: track.languageCode } : {}), fetch: f });
    const lines = toTranscriptLines(items as { text: string; offset: number }[]);
    if (!lines) throw new TranscriptFetchError(probe ? 'BLOCKED' : 'NO_CAPTIONS', 'empty transcript');
    const lang = track?.languageCode ?? (items[0] as { lang?: string } | undefined)?.lang ?? 'unknown';
    return { lines, language: lang, autoGenerated: track?.kind === 'asr' };
  } catch (err) {
    if (signal.aborted) throw new TranscriptFetchError('TIMEOUT', (err as Error)?.message ?? '');
    if (err instanceof TranscriptFetchError) throw err;
    throw new TranscriptFetchError(classifyError(err, probe), (err as Error)?.message ?? '');
  }
}

