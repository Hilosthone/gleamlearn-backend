import { YoutubeTranscriptDisabledError, YoutubeTranscriptNotAvailableError, YoutubeTranscriptTooManyRequestError, YoutubeTranscriptVideoUnavailableError } from 'youtube-transcript';
import { TRANSCRIPT_FAILURES, TranscriptFetchError, captionFormat, classifyError, classifyPlayability, fetchYoutubeTranscript, parseCaptionFile, pickTrack } from './youtube-transcript.js';
import { cachedCondensed, transcriptHash } from './learning.service.js';

const json = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status, headers: { 'Content-Type': 'application/json' } });
const player = (playabilityStatus: unknown, captionTracks?: unknown[]) =>
  json({ playabilityStatus, ...(captionTracks ? { captions: { playerCaptionsTracklistRenderer: { captionTracks } } } : {}) });

async function failure(p: Promise<unknown>) {
  try {
    await p;
  } catch (err) {
    expect(err).toBeInstanceOf(TranscriptFetchError);
    return (err as TranscriptFetchError).code;
  }
  throw new Error('expected a failure');
}

describe('caption track choice', () => {
  const tracks = [
    { languageCode: 'fr', kind: 'asr' },
    { languageCode: 'en', kind: 'asr' },
    { languageCode: 'fr' },
    { languageCode: 'en-GB' },
  ];

  it('prefers manual captions in a preferred language, then automatic ones, then anything', () => {
    expect(pickTrack(tracks)).toEqual({ languageCode: 'en-GB' });
    expect(pickTrack(tracks.slice(0, 3))).toEqual({ languageCode: 'en', kind: 'asr' });
    expect(pickTrack([{ languageCode: 'yo', kind: 'asr' }, { languageCode: 'ha' }])).toEqual({ languageCode: 'ha' });
    expect(pickTrack(tracks, ['fr', 'en'])).toEqual({ languageCode: 'fr' });
    expect(pickTrack([])).toBeNull();
  });
});

describe('failure classification', () => {
  it('reads the player API playability status', () => {
    expect(classifyPlayability({ status: 'OK' })).toBeNull();
    expect(classifyPlayability({ status: 'LOGIN_REQUIRED', reason: "Sign in to confirm you're not a bot" })).toBe('BLOCKED');
    expect(classifyPlayability({ status: 'LOGIN_REQUIRED', reason: 'This video is private' })).toBe('PRIVATE');
    expect(classifyPlayability({ status: 'AGE_CHECK_REQUIRED' })).toBe('AGE_RESTRICTED');
    expect(classifyPlayability({ status: 'UNPLAYABLE', reason: 'This video may be inappropriate for some users.' })).toBe('AGE_RESTRICTED');
    expect(classifyPlayability({ status: 'ERROR', reason: 'Video unavailable' })).toBe('UNAVAILABLE');
  });

  it('does not report a bot check as "no captions"', () => {
    const disabled = new YoutubeTranscriptDisabledError('abc');
    expect(classifyError(disabled, null)).toBe('BLOCKED');
    expect(classifyError(disabled, { playable: true, tracks: 3 })).toBe('BLOCKED');
    expect(classifyError(disabled, { playable: true, tracks: 0 })).toBe('NO_CAPTIONS');
    expect(classifyError(new YoutubeTranscriptTooManyRequestError(), null)).toBe('BLOCKED');
    expect(classifyError(new YoutubeTranscriptVideoUnavailableError('abc'), null)).toBe('UNAVAILABLE');
    expect(classifyError(new YoutubeTranscriptNotAvailableError('abc'), null)).toBe('BLOCKED');
    expect(classifyError(new TypeError('fetch failed'), null)).toBe('NETWORK');
  });

  it('every failure has a learner message', () => {
    for (const f of Object.values(TRANSCRIPT_FAILURES)) expect(f.message.length).toBeGreaterThan(20);
  });
});

describe('fetching a transcript', () => {
  const items = [
    { text: 'Hello', offset: 0, duration: 1 },
    { text: 'World', offset: 65, duration: 1 },
  ];

  it('picks the best track and asks the library for that language', async () => {
    const fetchTrack = vi.fn().mockResolvedValue(items);
    const t = await fetchYoutubeTranscript('abcdefghijk', {
      fetch: vi.fn().mockResolvedValue(player({ status: 'OK' }, [{ languageCode: 'de' }, { languageCode: 'en', kind: 'asr' }])) as never,
      fetchTrack,
    });
    expect(t).toEqual({ lines: '[00:00] Hello\n[01:05] World', language: 'en', autoGenerated: true });
    expect(fetchTrack.mock.calls[0][1].lang).toBe('en');
  });

  it('a playable video without captions is NO_CAPTIONS (the library is not called)', async () => {
    const fetchTrack = vi.fn();
    expect(await failure(fetchYoutubeTranscript('abcdefghijk', { fetch: vi.fn().mockResolvedValue(player({ status: 'OK' })) as never, fetchTrack }))).toBe('NO_CAPTIONS');
    expect(fetchTrack).not.toHaveBeenCalled();
  });

  it('bot check, private, age restriction and 429 are named', async () => {
    const run = (r: Response) => failure(fetchYoutubeTranscript('abcdefghijk', { fetch: vi.fn().mockResolvedValue(r) as never, fetchTrack: vi.fn() }));
    expect(await run(player({ status: 'LOGIN_REQUIRED', reason: "Sign in to confirm you're not a bot" }))).toBe('BLOCKED');
    expect(await run(player({ status: 'LOGIN_REQUIRED', reason: 'This video is private' }))).toBe('PRIVATE');
    expect(await run(player({ status: 'AGE_CHECK_REQUIRED' }))).toBe('AGE_RESTRICTED');
    expect(await run(json({}, 429))).toBe('BLOCKED');
  });

  it('when the player API gives no verdict, the library error is classified', async () => {
    const fetchTrack = vi.fn().mockRejectedValue(new YoutubeTranscriptDisabledError('abcdefghijk'));
    expect(await failure(fetchYoutubeTranscript('abcdefghijk', { fetch: vi.fn().mockResolvedValue(json({}, 500)) as never, fetchTrack }))).toBe('BLOCKED');
  });

  it('a slow YouTube is a TIMEOUT, not a hang', async () => {
    const hang = ((_: unknown, init?: RequestInit) =>
      new Promise((_r, reject) => init?.signal?.addEventListener('abort', () => reject(Object.assign(new Error('aborted'), { name: 'AbortError' }))))) as never;
    const fetchTrack = vi.fn((_id: string, cfg: { fetch: typeof fetch }) => cfg.fetch('https://www.youtube.com/watch?v=x') as never);
    expect(await failure(fetchYoutubeTranscript('abcdefghijk', { fetch: hang, fetchTrack, timeoutMs: 50 }))).toBe('TIMEOUT');
  });
});

describe('caption files', () => {
  it('parses WebVTT: markup, settings, notes and rolling duplicates are removed', () => {
    const vtt = [
      'WEBVTT',
      'Kind: captions',
      '',
      'NOTE this is a note',
      '',
      '00:00:01.000 --> 00:00:03.000 align:start position:0%',
      'Photosynthesis <c>is</c> how',
      'plants make food',
      '',
      '00:00:03.000 --> 00:00:05.000',
      'Photosynthesis is how plants make food',
      '',
      '01:02:05.500 --> 01:02:07.000',
      '<i>Chlorophyll</i> absorbs &amp; reflects light',
    ].join('\n');
    expect(parseCaptionFile(vtt)).toBe('[00:01] Photosynthesis is how plants make food\n[1:02:05] Chlorophyll absorbs & reflects light');
    expect(captionFormat(vtt)).toBe('vtt');
  });

  it('parses SubRip with Windows line endings', () => {
    const srt = '1\r\n00:00:00,500 --> 00:00:02,000\r\nHello there\r\n\r\n2\r\n00:01:05,000 --> 00:01:06,000\r\nGeneral Kenobi\r\n';
    expect(parseCaptionFile(srt)).toBe('[00:00] Hello there\n[01:05] General Kenobi');
    expect(captionFormat(srt)).toBe('srt');
  });

  it('anything else is not a caption file', () => {
    expect(captionFormat('just some notes')).toBeNull();
    expect(captionFormat('just some notes', 'srt')).toBe('srt');
    expect(parseCaptionFile('just some notes')).toBe('');
  });
});

describe('condensed transcript cache', () => {
  it('is reused only for the transcript it was made from', () => {
    const transcript = '[00:00] a long transcript';
    const structured = { session: {}, condensed: { hash: transcriptHash(transcript), text: 'notes', chars: 999, truncated: true } };
    expect(cachedCondensed(structured, transcript)).toEqual({ text: 'notes', chars: 999, truncated: true });
    expect(cachedCondensed(structured, transcript + ' edited')).toBeNull();
    expect(cachedCondensed({ session: {} }, transcript)).toBeNull();
    expect(cachedCondensed(null, transcript)).toBeNull();
  });
});
